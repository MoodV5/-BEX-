/**
 * Build migrated reference pages from data/reference-content.json.
 * Run: node scripts/build-reference-pages.mjs
 * Shared shell: vm1.html. Edit data or this renderer, not generated HTML.
 */
import { existsSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { pageFiles } from './site-config.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
if (process.argv.includes('--help')) {
    console.log('使い方: node scripts/build-reference-pages.mjs [--check]\n引数なし: ページ・共通部品を生成します。\n--check: 一致確認のみ。原本を書き換えません。');
    process.exit(0);
}
if (process.argv.slice(2).some(argument => argument !== '--check')) throw new Error('不明な引数です。--help で確認してください。');
const data = JSON.parse(readFileSync(join(root, 'data/reference-content.json'), 'utf8'));
const template = readFileSync(join(root, 'vm1.html'), 'utf8');
const origin = 'https://www.bex.co.jp/';
const marker = '<!-- Generated by scripts/build-reference-pages.mjs; edit data/reference-content.json or the renderer. -->';
const checkOnly = process.argv.includes('--check');
const outputs = new Map();
const readPage = file => outputs.get(file) ?? readFileSync(join(root, file), 'utf8');
const normalized = text => text.replaceAll('\r\n', '\n');
const escapeHtml = value => String(value).replace(/[&<>"']/g, char => ({
    '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;'
}[char]));

function relatedLinks(exclude) {
    const links = [
        ['concept.html', '会社概要'],
        ['concept_3.html', '納入実績'],
        ['concept_4.html', '取引先メーカー'],
        ['vm1.html', 'Visual Master・スクリーン'],
        ['contact.html', 'お問い合わせ']
    ];
    return `<nav class="reference-related" aria-label="関連ページ">${links
        .filter(([href]) => href !== exclude)
        .map(([href, label]) => `<a href="${href}">${escapeHtml(label)}</a>`).join('')}</nav>`;
}

function buildPage({ file, title, heading, description, image, imageAlt, body, parent }) {
    const breadcrumbItems = [
        { name: 'ホーム', url: origin },
        { name: parent.name, url: origin + parent.file },
        { name: heading, url: origin + file }
    ];
    const schema = {
        '@context': 'https://schema.org',
        '@graph': [
            {
                '@type': 'WebPage', '@id': origin + file + '#webpage',
                name: title, description, url: origin + file, inLanguage: 'ja',
                about: { '@id': origin + '#organization' },
                isPartOf: { '@id': origin + '#website' }
            },
            {
                '@type': 'BreadcrumbList',
                itemListElement: breadcrumbItems.map((item, index) => ({
                    '@type': 'ListItem', position: index + 1, name: item.name, item: item.url
                }))
            }
        ]
    };
    let html = template
        .replace('<!DOCTYPE html>', `<!DOCTYPE html>\n${marker}`)
        .replace(/<body>/, '<body class="reference-page">')
        .replace(/<title>[\s\S]*?<\/title>/, `<title>${escapeHtml(title)}</title>`)
        .replace(/<meta name="description" content="[^"]*">/, `<meta name="description" content="${escapeHtml(description)}">`)
        .replace(/<link rel="canonical" href="[^"]*">/, `<link rel="canonical" href="${origin + file}">`)
        .replace(/<script type="application\/ld\+json">[\s\S]*?<\/script>/, () => `<script type="application/ld+json">\n${JSON.stringify(schema, null, 2)}\n    </script>`)
        .replace(/<h1 class="hero-title">[\s\S]*?<\/h1>/, () => `<h1 class="hero-title">${escapeHtml(heading)}</h1>`)
        .replace(/<p class="hero-desc">[\s\S]*?<\/p>/, () => `<p class="hero-desc">${escapeHtml(description)}</p>`)
        .replace(/<div class="hero-bg"[^>]*><\/div>/, `<div class="hero-bg" style="background-image: url('${image}');"></div>`)
        .replace(/<main class="main-content">[\s\S]*?<\/main>/, () => `<main class="main-content">\n        <div class="container content-card reference-content">\n${body}\n${relatedLinks(file)}\n        </div>\n    </main>`);
    const meta = { title, description, url: origin + file, image: origin + image, 'image:alt': imageAlt };
    for (const [property, value] of Object.entries(meta)) {
        html = html.replace(new RegExp(`<meta property="og:${property}" content="[^"]*">`), `<meta property="og:${property}" content="${escapeHtml(value)}">`);
    }
    const target = join(root, file);
    if (existsSync(target) && !readFileSync(target, 'utf8').includes(marker)) {
        throw new Error(`Refusing to overwrite non-generated page: ${file}`);
    }
    outputs.set(file, html);
}

