function drawingLink(document, model, format) {
    const target = join(root, document.path);
    if (!existsSync(target)) throw new Error(`Missing document: ${document.path}`);
    const bytes = statSync(target).size;
    const pdf = format === 'PDF';
    const label = pdf ? `PDF（${Math.ceil(bytes / 1024)} KB）` : `DXF（ZIP・${Math.ceil(bytes / 1024)} KB）`;
    const attributes = pdf ? 'target="_blank" rel="noopener"' : 'download';
    const action = pdf ? 'を別タブで表示' : 'をダウンロード';
    return `<a class="drawing-link" href="${document.path}" ${attributes} aria-label="${escapeHtml(model)} 外観詳細図 ${format}${action}">${label}</a>`;
}

