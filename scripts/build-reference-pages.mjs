function syncSharedParts() {
    // Authoring comments belong in the source snippets, not repeated output.
    const snippet = file => readFileSync(join(root, 'partials', file), 'utf8').replace(/^<!--[\s\S]*?-->\s*/, '').trim();
    const header = snippet('header.html');
    const footer = snippet('footer.html');
    const assets = ['style.css', 'reference.css', 'contact.css', 'main.js', 'contact.js', 'images/bex-logo.jpg'];
    const versions = new Map(assets.map(file => {
        const bytes = readFileSync(join(root, file));
        const content = file.endsWith('.jpg') ? bytes : normalized(bytes.toString('utf8'));
        return [file, createHash('sha256').update(content).digest('hex').slice(0, 12)];
    }));
    for (const file of pageFiles) {
        let html = readPage(file);
        for (const [tag, content] of [['header', header], ['footer', footer]]) {
            const pattern = new RegExp(`<${tag} class="site-${tag}">[\\s\\S]*?</${tag}>`, 'g');
            if ([...html.matchAll(pattern)].length !== 1) throw new Error(`${file}: ${tag} が1つではありません。HTML構造を確認してください。`);
            html = html.replace(pattern, () => content
                .replaceAll('{{HOME_CURRENT}}', file === 'index.html' ? ' aria-current="page"' : '')
                .replaceAll('{{BUSINESS_HREF}}', file === 'index.html' ? '#business' : 'index.html#business'));
        }
        // Content hashes refresh cached assets only when their contents change.
        html = html.replace(/\b(src|href)="([^"?]+)(?:\?[^"#]*)?"/g, (match, attribute, asset) =>
            versions.has(asset) ? `${attribute}="${asset}?v=${versions.get(asset)}"` : match);
        if (/\{\{(?:HOME_CURRENT|BUSINESS_HREF)\}\}/.test(html)) throw new Error(`${file}: 共通部品の置換に失敗しました。`);
        outputs.set(file, html);
    }
}

function syncSitemap() {
    const path = join(root, 'sitemap.xml');
    let sitemap = readFileSync(path, 'utf8');
    const newFiles = ['concept_3.html', 'concept_4.html', ...data.screenSeries.map(series => series.page)];
    for (const file of ['index.html', 'concept.html', 'eizoonkyo.html', 'vm1.html', ...newFiles]) {
        const url = file === 'index.html' ? origin : origin + file;
        const existing = new RegExp(`  <url>\\s*<loc>${url.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}</loc>[\\s\\S]*?</url>`);
        // A later editorial review must not be dated back to the source migration.
        const previousDate = sitemap.match(existing)?.[0].match(/<lastmod>(\d{4}-\d{2}-\d{2})<\/lastmod>/)?.[1];
        const updatedDate = previousDate && previousDate > data.sourceDate ? previousDate : data.sourceDate;
        const entry = `  <url>\n    <loc>${url}</loc>\n    <lastmod>${updatedDate}</lastmod>\n  </url>`;
        sitemap = existing.test(sitemap) ? sitemap.replace(existing, () => entry) : sitemap.replace('</urlset>', `${entry}\n</urlset>`);
    }
    outputs.set('sitemap.xml', sitemap);
}

buildCustomers();
buildMakers();
data.screenSeries.forEach(buildScreen);
syncSharedParts();
syncSitemap();
// Validate everything before writing, and avoid touching unchanged files.
const changed = [...outputs].filter(([file, html]) => !existsSync(join(root, file)) || normalized(readFileSync(join(root, file), 'utf8')) !== normalized(html));
if (checkOnly && changed.length) {
    console.error(`再生成が必要です: ${changed.map(([file]) => file).join(', ')}\n実行してください: npm run generate`);
    process.exitCode = 1;
} else if (checkOnly) {
    console.log('PASS 生成ページ・共通ヘッダー・フッター・画像/CSS/JSの更新番号・サイトマップが一致しています（書き込みなし）。');
} else {
    for (const [file, html] of changed) writeFileSync(join(root, file), normalized(html));
    console.log(`生成・同期完了: ${changed.length}ファイル更新。${pageFiles.length}ページの共通部品、実績${data.customers.length}件、メーカー${data.makers.length}件を確認。`);
}
