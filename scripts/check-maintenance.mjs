// Offline documentation and page-registry checks; never writes source files.
import assert from 'node:assert/strict';
import { existsSync, readFileSync, readdirSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { root, pages, pageFiles } from './site-config.mjs';

const actual = readdirSync(root).filter(file => file.endsWith('.html')).sort();
assert.deepEqual(actual, [...pageFiles].sort(), '公開HTMLと data/site-pages.json の一覧が一致していません。');
const generated = '<!-- Generated by scripts/build-reference-pages.mjs;';
for (const page of pages) {
    assert.equal(readFileSync(join(root, page.file), 'utf8').includes(generated), page.generated, `${page.file}: generated の指定が実際と異なります。`);
}
const guide = readFileSync(join(root, 'docs/MAINTENANCE.md'), 'utf8');
for (const file of pageFiles) assert(guide.includes('`' + file + '`'), `更新手順に ${file} を追加してください。`);
const documents = ['README.md', 'data/README.md', 'deployment/SECURITY.md', 'docs/MAINTENANCE.md', 'docs/HANDOVER.md', 'docs/RELEASE.md'];
let links = 0;
for (const file of documents) {
    const content = readFileSync(join(root, file), 'utf8');
    assert(!content.includes('\uFFFD'), `${file}: 文字化けがあります。`);
    for (const [, target] of content.matchAll(/\]\(([^)]+)\)/g)) {
        if (/^(?:https?:|#)/.test(target)) continue;
        const path = resolve(root, file, '..', target.split('#')[0]);
        assert(existsSync(path), `${file}: 手順書のリンク切れ ${target}`);
        links++;
    }
}
const packageJson = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
for (const name of ['generate', 'check', 'preview', 'build', 'test:layout', 'test:contact']) assert(packageJson.scripts[name], `コマンド未定義: ${name}`);
assert(packageJson.private === true && !packageJson.dependencies && !packageJson.devDependencies, '基本操作は追加パッケージ不要のまま維持します。');
console.log(`PASS 管理情報: ${pages.length}ページ、手順書${documents.length}件、内部リンク${links}件。`);
